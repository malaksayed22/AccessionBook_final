import "server-only";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { GetObjectCommand, PutObjectCommand, S3Client } from "@aws-sdk/client-s3";
import { env } from "./env";

/**
 * Where uploaded files live. They are never served by the web server directly: every download goes
 * through an authenticated route. The disk driver is for development and tests; production uses
 * the S3 driver against a private, encrypted bucket (see docs/storage.md). Both sit behind this
 * interface, so callers never know which one they have.
 */
export interface BlobStorage {
  /** Write-once: throws `StorageKeyExistsError` when the key is already stored. */
  put(key: string, data: Buffer): Promise<void>;
  /** Returns null when the key does not exist. */
  get(key: string): Promise<Buffer | null>;
}

export class StorageKeyExistsError extends Error {
  constructor(key: string) {
    super(`Storage key already exists: ${key}`);
    this.name = "StorageKeyExistsError";
  }
}

const MAX_KEY_LENGTH = 512;
const CONTROL_CHARACTERS = /[\u0000-\u001f\u007f]/;

/**
 * Keys are generated by the server, but both drivers still refuse anything that could escape the
 * storage root or prefix: empty, absolute, backslashes, `.`/`..`/empty segments, control characters.
 */
export function assertSafeKey(key: string): void {
  const valid =
    key.length > 0 &&
    key.length <= MAX_KEY_LENGTH &&
    !key.startsWith("/") &&
    !key.includes("\\") &&
    !CONTROL_CHARACTERS.test(key) &&
    key.split("/").every((segment) => segment !== "" && segment !== "." && segment !== "..");
  if (!valid) throw new Error("Invalid storage key");
}

export class LocalDiskStorage implements BlobStorage {
  constructor(private readonly root: string) {}

  private resolve(key: string): string {
    assertSafeKey(key);
    const full = path.resolve(this.root, key);
    // Defence in depth: whatever the key looks like, the resolved path stays under the root.
    if (!full.startsWith(this.root + path.sep)) throw new Error("Invalid storage key");
    return full;
  }

  async put(key: string, data: Buffer): Promise<void> {
    const full = this.resolve(key);
    await mkdir(path.dirname(full), { recursive: true });
    try {
      // `wx`: a key is written once and never overwritten.
      await writeFile(full, data, { flag: "wx" });
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "EEXIST") throw new StorageKeyExistsError(key);
      throw error;
    }
  }

  async get(key: string): Promise<Buffer | null> {
    try {
      return await readFile(this.resolve(key));
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === "ENOENT") return null;
      throw error;
    }
  }
}

/** The one method of `S3Client` the driver needs; tests inject a fake. */
export type S3Sender = { send(command: unknown): Promise<unknown> };

type S3StorageOptions = {
  client: S3Sender;
  bucket: string;
  /** KMS key id or ARN for SSE-KMS; without it objects use SSE-S3 (AES256). */
  kmsKeyId?: string;
};

type S3ErrorShape = { name?: string; $metadata?: { httpStatusCode?: number } };

function isS3Error(error: unknown, name: string, status: number): boolean {
  const { name: errorName, $metadata } = (error ?? {}) as S3ErrorShape;
  return errorName === name || $metadata?.httpStatusCode === status;
}

async function readAll(body: unknown): Promise<Buffer> {
  if (body === null || typeof body !== "object" || !(Symbol.asyncIterator in body)) {
    throw new Error("Unexpected S3 response body");
  }
  const chunks: Buffer[] = [];
  for await (const chunk of body as AsyncIterable<Uint8Array | string>) {
    chunks.push(Buffer.from(chunk));
  }
  return Buffer.concat(chunks);
}

export class S3Storage implements BlobStorage {
  private readonly client: S3Sender;
  private readonly bucket: string;
  private readonly kmsKeyId: string | undefined;

  constructor({ client, bucket, kmsKeyId }: S3StorageOptions) {
    this.client = client;
    this.bucket = bucket;
    this.kmsKeyId = kmsKeyId;
  }

  async put(key: string, data: Buffer): Promise<void> {
    assertSafeKey(key);
    try {
      await this.client.send(
        new PutObjectCommand({
          Bucket: this.bucket,
          Key: key,
          Body: data,
          ChecksumAlgorithm: "SHA256",
          // Never overwrite: S3 answers 412 PreconditionFailed when the key exists.
          IfNoneMatch: "*",
          ...(this.kmsKeyId
            ? { ServerSideEncryption: "aws:kms", SSEKMSKeyId: this.kmsKeyId }
            : { ServerSideEncryption: "AES256" }),
        })
      );
    } catch (error) {
      if (isS3Error(error, "PreconditionFailed", 412)) throw new StorageKeyExistsError(key);
      throw error;
    }
  }

  async get(key: string): Promise<Buffer | null> {
    assertSafeKey(key);
    try {
      const response = (await this.client.send(
        new GetObjectCommand({ Bucket: this.bucket, Key: key })
      )) as { Body?: unknown };
      return await readAll(response.Body);
    } catch (error) {
      if (isS3Error(error, "NoSuchKey", 404)) return null;
      throw error;
    }
  }
}

let instance: BlobStorage | undefined;

export function storage(): BlobStorage {
  instance ??= createStorage();
  return instance;
}

function createStorage(): BlobStorage {
  const config = env();
  if (config.STORAGE_DRIVER === "s3") {
    // `parseEnv` already requires the bucket for s3; this narrows the type.
    if (!config.S3_BUCKET) throw new Error("S3_BUCKET is required when STORAGE_DRIVER=s3");
    // Credentials come from the default provider chain (the task role in production); no keys
    // are configured anywhere.
    return new S3Storage({
      client: new S3Client({ region: config.S3_REGION }),
      bucket: config.S3_BUCKET,
      kmsKeyId: config.S3_KMS_KEY_ID,
    });
  }
  return new LocalDiskStorage(path.resolve(config.STORAGE_DIR));
}
